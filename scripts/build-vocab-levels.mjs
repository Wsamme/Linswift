import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const sourcePath = path.join(root, 'src/data/vocab-test/30k.txt')
const outputPath = path.join(root, 'src/data/vocab-test/openSourceVocabLevels.ts')
const properNounsPath = path.join(root, 'src/data/vocab-test/properNouns.ts')

const VOCAB_LEVEL_TARGETS = [500, 1000, 2000, 3500, 5000, 7000, 9500, 12500, 16000, 20000]
const PUBLIC_VOCAB_TOTAL_WORDS = 20000
const SHORT_WORD_WHITELIST = new Set([
  'a', 'i',
  'am', 'an', 'as', 'at', 'be', 'by', 'do', 'go', 'he', 'if', 'in', 'is', 'it',
  'me', 'my', 'no', 'of', 'on', 'or', 'ox', 'to', 'up', 'us', 'we',
])
const ABBREVIATION_BLACKLIST = new Set([
  'api', 'sdk', 'sql', 'html', 'css', 'js', 'json', 'xml', 'http', 'https',
  'tcp', 'udp', 'dns', 'ip', 'cpu', 'gpu', 'ram', 'ssd', 'usb',
  'pdf', 'jpg', 'jpeg', 'png', 'gif', 'svg', 'php', 'ios', 'ai',
  'mba', 'phd', 'ceo', 'cfo', 'cto', 'hr',
])

function loadProperNouns(filePath) {
  const source = fs.readFileSync(filePath, 'utf8')
  const matches = [...source.matchAll(/'([^']+)'/g)]
  return new Set(matches.map((match) => match[1]))
}

function isValidCandidate(word, properNouns) {
  if (!/^[a-z]+(?:['-][a-z]+)*$/.test(word)) return false
  if (word.length < 2 || word.length > 24) return false
  if (!/[aeiouy]/.test(word)) return false
  if (word.length <= 2 && !SHORT_WORD_WHITELIST.has(word)) return false
  if (ABBREVIATION_BLACKLIST.has(word)) return false
  if (properNouns.has(word)) return false
  return true
}

const raw = fs.readFileSync(sourcePath, 'utf8')
const properNouns = loadProperNouns(properNounsPath)
const unique = new Set()

for (const line of raw.split('\n')) {
  const [first] = line.split('\t')
  const word = (first || '').trim().toLowerCase()
  if (!word) continue
  if (!isValidCandidate(word, properNouns)) continue
  unique.add(word)
}

const cleanedWords = [...unique]
const words = cleanedWords.slice(0, PUBLIC_VOCAB_TOTAL_WORDS)
const levelCount = VOCAB_LEVEL_TARGETS.length

const levels = []
for (let i = 0; i < levelCount; i += 1) {
  const start = i === 0 ? 0 : VOCAB_LEVEL_TARGETS[i - 1]
  const end = VOCAB_LEVEL_TARGETS[i]
  levels.push(words.slice(start, end))
}

const file = [
  '/**',
  ' * Open-source vocabulary levels for test mode.',
  ' * Source: https://github.com/arstgit/high-frequency-vocabulary (MIT)',
  ' * Generated by scripts/build-vocab-levels.mjs',
  ' */',
  '',
  `export const VOCAB_LEVEL_COUNT = ${levelCount} as const`,
  'export const VOCAB_LEVEL_PASS_SCORE = 7 as const',
  'export const VOCAB_WORDS_PER_LEVEL_TEST = 10 as const',
  `export const PUBLIC_VOCAB_TOTAL_WORDS = ${PUBLIC_VOCAB_TOTAL_WORDS} as const`,
  `export const VOCAB_LEVEL_TARGETS = ${JSON.stringify(VOCAB_LEVEL_TARGETS)} as const`,
  `export const PUBLIC_VOCAB_CANDIDATE_COUNT = ${cleanedWords.length}`,
  '',
  `export const VOCAB_LEVELS: string[][] = ${JSON.stringify(levels, null, 2)}`,
  '',
  'export function randomSampleWords(source: string[], count: number): string[] {',
  '  const pool = [...source]',
  '  for (let i = pool.length - 1; i > 0; i -= 1) {',
  '    const j = Math.floor(Math.random() * (i + 1))',
  '    ;[pool[i], pool[j]] = [pool[j], pool[i]]',
  '  }',
  '  return pool.slice(0, Math.min(count, pool.length))',
  '}',
  '',
].join('\n')

fs.writeFileSync(outputPath, file)
console.log(`Generated ${outputPath} with ${words.length} public-core words from ${cleanedWords.length} cleaned candidates.`)
