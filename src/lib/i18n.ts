export function getLanguageLabel(lang: AppLanguage): string {
  if (lang === 'en') return 'English'
  if (lang === 'ja') return '日本語'
  return '简体中文'
}

export function t(lang: AppLanguage, key: keyof (typeof messages)['zh-CN']): string {
  return messages[lang]?.[key] || messages['zh-CN'][key]
}

export function tf(lang: AppLanguage, key: keyof (typeof messages)['zh-CN'], vars: Record<string, string | number>): string {
  const template = t(lang, key)
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}

export function useAppLanguage() {
  const [lang, setLang] = useState<AppLanguage>(() => loadThemeSettings().language)

  useEffect(() => {
    const sync = () => setLang(loadThemeSettings().language)
    window.addEventListener(THEME_CHANGE_EVENT, sync)
    return () => window.removeEventListener(THEME_CHANGE_EVENT, sync)
  }, [])

  return lang
}
