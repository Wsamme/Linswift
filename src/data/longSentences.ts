import type {
  LongSentenceAnalysis,
  LongSentenceClause,
  LongSentenceConnector,
  LongSentenceReadingItem,
  LongSentenceRole,
  LongSentenceSegment,
  LongSentenceWritingPrompt,
} from '../lib/longSentence'

type SegmentInput = [string, LongSentenceRole, string]
type ConnectorInput = [string, string]

interface ReadingSeed {
  id: string
  title: string
  category: string
  difficulty: '中阶' | '进阶' | '高阶'
  focus: string
  sentence: string
  translation: string
  segments: SegmentInput[]
  connectors?: ConnectorInput[]
  clauses?: Array<{ label: string; text: string; function: string; simplified: string }>
  simpleRewrites?: string[]
  grammarPoints?: string[]
}

function seg([text, role, note]: SegmentInput): LongSentenceSegment {
  return { text, role, note }
}

function cn([text, func]: ConnectorInput): LongSentenceConnector {
  return { text, function: func }
}

function autoClauses(sentence: string): LongSentenceClause[] {
  return sentence
    .split(/,\s*/)
    .map((part) => part.trim())
    .filter(Boolean)
    .map((text, index) => ({
      label: `意群 ${index + 1}`,
      text,
      function: index === 0 ? '先找主句起点或让步/条件提示词。' : '把这一块作为补充信息回挂到主句。',
      simplified: text,
    }))
}

function toReadingItem(seed: ReadingSeed): LongSentenceReadingItem {
  const analysis: LongSentenceAnalysis = {
    sentence: seed.sentence,
    translation: seed.translation,
    summary: `这句重点训练：${seed.focus}。先沿连接词分块，再抓每块里的主谓宾。`,
    segments: seed.segments.map(seg),
    clauses: seed.clauses ?? autoClauses(seed.sentence),
    grammarPoints: seed.grammarPoints ?? [
      `核心焦点：${seed.focus}`,
      '先读主句，再把从句当作补充条件、原因、让步或结果挂回去。',
      '把原句拆成 2 到 3 个短句之后，再回看原句更容易稳住结构。',
    ],
    connectors: (seed.connectors ?? []).map(cn),
    simpleRewrites: seed.simpleRewrites ?? autoClauses(seed.sentence).map((item) => item.simplified),
  }

  return {
    id: seed.id,
    title: seed.title,
    category: seed.category,
    difficulty: seed.difficulty,
    focus: seed.focus,
    sentence: seed.sentence,
    analysis,
  }
}

